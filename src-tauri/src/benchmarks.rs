/// El baremo de una métrica para una población concreta.
///
/// `band` es el tramo (`"bajo"`, `"medio"`, `"alto"`); `None` —o un tramo que
/// no exista— cae al baremo del puesto sobre el corpus entero, que es lo
/// correcto cuando no se sabe en qué rango se jugó la partida. Perder el tramo
/// degrada la comparación pero no la invalida: el efecto del puesto es mucho
/// mayor que el del rango.
pub fn benchmark(metric: &str, band: Option<&str>, role: &str) -> Option<Benchmark> {
    if let Some(b) = band {
        if let Some((_, _, _, d)) = DECILES_POR_TRAMO
            .iter()
            .find(|(m, t, r, _)| *m == metric && *t == b && *r == role)
        {
            return Some(Benchmark { metric: METRICAS.iter().find(|x| **x == metric)?, deciles: *d });
        }
    }
    let (_, _, d) = DECILES_POR_ROL
        .iter()
        .find(|(m, r, _)| *m == metric && *r == role)?;
    Some(Benchmark { metric: METRICAS.iter().find(|x| **x == metric)?, deciles: *d })
}

/// Los nueve cortes del 10% al 90%.
pub fn deciles(metric: &str, band: Option<&str>, role: &str) -> Option<[f64; 9]> {
    benchmark(metric, band, role).map(|b| b.deciles)
}

/// La mediana de la población: el corte del 50%, o sea el quinto decil.
pub fn median(metric: &str, band: Option<&str>, role: &str) -> Option<f64> {
    deciles(metric, band, role).map(|d| d[4])
}

/// En qué percentil (0..100) cae `value` entre los jugadores de ese tramo y
/// puesto. `None` si la métrica o el puesto no existen.
///
/// **Siempre es el percentil crudo**, también para `deaths_per_game`: morir
/// mucho da percentil alto. Invertirlo aquí escondería el signo dentro de una
/// tabla y tarde o temprano alguien lo pintaría al revés; en vez de eso la
/// dirección se consulta por separado con [`lower_is_better`] y la UI decide si
/// pinta el 90 en verde o en rojo.
pub fn percentile(metric: &str, band: Option<&str>, role: &str, value: f64) -> Option<u8> {
    let d = deciles(metric, band, role)?;
    Some(interpolar(&d, value).round().clamp(0.0, 100.0) as u8)
}

/// Si en esta métrica lo bueno es tener *menos*.
///
/// Sólo las muertes. `deaths_per_game` está en el baremo porque es de lo
/// primero que mira un jugador, no porque un percentil alto sea un elogio.
pub fn lower_is_better(metric: &str) -> bool {
    metric == "deaths_per_game"
}

/// El tramo en que cae un rango de Riot (`"IRON"`..`"CHALLENGER"`).
///
/// Copia deliberada de la tabla `TRAMOS` de `tools/corpus/fetch_tiers.py`, que
/// es la **fuente de la verdad**: es el script que etiquetó el `tiers.json` con
/// el que se midieron estas constantes. Si allí se reagrupan los rangos, aquí
/// hay que reagruparlos igual y volver a medir; si no, los percentiles pasan a
/// comparar contra una población que ya no es la que dicen ser.
///
/// Devuelve `""` para un rango desconocido o sin clasificar, que es lo que
/// [`percentile`] interpreta como "sin tramo" y hace caer al baremo del puesto.
pub fn band_for_tier(tier: &str) -> &'static str {
    match tier.to_ascii_uppercase().as_str() {
        "IRON" | "BRONZE" | "SILVER" => "bajo",
        "GOLD" | "PLATINUM" | "EMERALD" => "medio",
        "DIAMOND" | "MASTER" | "GRANDMASTER" | "CHALLENGER" => "alto",
        _ => "",
    }
}

/// Una métrica del jugador puesta al lado de la población que le corresponde.
///
/// Es la unidad que consume la UI: el valor crudo para enseñarlo, el percentil
/// para el "mejor que el 72%", la mediana para el "la media de tu rango es X" y
/// la dirección para saber si el 72 es bueno o malo.
#[derive(Debug, Clone, Serialize)]
pub struct MetricComparison {
    pub metric: String,
    pub value: f64,
    pub percentile: Option<u8>,
    pub median: Option<f64>,
    pub lower_is_better: bool,
}

/// Compara de golpe todas las métricas de una partida.
///
/// Las métricas que no estén en el baremo (o un puesto desconocido) salen igual
/// en la lista, con `percentile` y `median` a `None`: la UI necesita poder
/// enseñar el valor aunque no haya con qué compararlo.
pub fn compare_all(band: Option<&str>, role: &str, values: &[(&str, f64)]) -> Vec<MetricComparison> {
    values
        .iter()
        .map(|(m, v)| MetricComparison {
            metric: (*m).to_string(),
            value: *v,
            percentile: percentile(m, band, role, *v),
            median: median(m, band, role),
            lower_is_better: lower_is_better(m),
        })
        .collect()
}

/// Interpola el percentil entre deciles.
///
/// El caso difícil no es interpolar sino los **empates**: métricas discretas
/// como `deaths_per_game`, `control_wards` o `solo_kills` tienen cortes
/// repetidos (los deciles de centinelas de control en TOP son
/// `[0,0,0,0,0,0,0,1,2]`). Con la interpolación de toda la vida, "0 centinelas"
/// dividiría por un hueco de cero.
///
/// Un bloque empatado se resuelve con el rango medio: si el valor coincide con
/// los cortes del 10% al 70%, el percentil es 35 — el centro del bloque de
/// gente que hizo exactamente eso. Y encaja por los dos lados con la
/// interpolación normal, así que la función sigue siendo monótona.
fn interpolar(cortes: &[f64; 9], v: f64) -> f64 {
    let menores = cortes.iter().filter(|c| **c < v).count();
    let iguales = cortes.iter().filter(|c| **c == v).count();

    // Bloque empatado de dos o más cortes: rango medio.
    if iguales >= 2 {
        return 5.0 * (2 * menores + iguales) as f64;
    }

    let i = menores;
    if i == 0 {
        // Por debajo del primer decil: se extrapola con el ancho del primer
        // hueco. No se puede dividir por `cortes[0]` como en `baselines`
        // porque aquí hay métricas que valen cero (o negativas) en el decil 1.
        let hueco = (cortes[1] - cortes[0]).abs().max(1e-9);
        return (10.0 - 10.0 * (cortes[0] - v) / hueco).max(0.0);
    }
    if i == 9 {
        let hueco = (cortes[8] - cortes[7]).abs().max(1e-9);
        return (90.0 + 10.0 * (v - cortes[8]) / hueco).min(100.0);
    }
    let hueco = (cortes[i] - cortes[i - 1]).max(1e-9);
    10.0 * (i as f64 + (v - cortes[i - 1]) / hueco)
}

