//! Baremos de población: "un jungla de tu rango hace 6,2 de CS por minuto".
//!
//! La app sabía comparar al jugador consigo mismo (sus otras partidas) y con
//! los otros nueve de su lobby. Las dos comparaciones se quedan cortas: la
//! primera no dice si vas bien o mal en absoluto —sólo si vas mejor que ayer— y
//! la segunda depende de si te tocó un lobby flojo. Lo que hay que poder
//! contestar es *"¿esto es bueno para alguien como yo?"*, y eso exige una
//! población: todos los que juegan tu puesto en tu rango.
//!
//! Aquí están los deciles de 17 métricas por partida, medidos sobre el corpus
//! local y pegados como constantes. Igual que en [`crate::baselines`], los
//! números no se ponen a ojo: los calcula `tools/corpus/fit_benchmarks.py`, los
//! imprime listos para pegar, y la prueba `recalcular_desde_corpus` comprueba
//! que los compilados sigan cuadrando con el corpus.
//!
//! **Medido el 2026-09-02** sobre 12.888 partidas válidas de las 12.974 del
//! corpus (todas clasificatoria solo, cola 420, LA1). Las 86 restantes son
//! remakes y rendiciones tempranas, que se descartan: por debajo de 900 s nadie
//! llega a minuto 15, los diffs no existen y las tasas por minuto salen
//! infladas por la fase de líneas.
//!
//! # Los tramos
//!
//! Tres, no diez, porque cada celda es (tramo x puesto): con diez rangos harían
//! falta 50 celdas con muestra suficiente. La definición es la de
//! `tools/corpus/fetch_tiers.py`, **que es la fuente de la verdad** y la que
//! produjo el `tiers.json` con el que se midió esto:
//!
//! ```text
//!   bajo   Hierro, Bronce, Plata          n = 8.145 partidas
//!   medio  Oro, Platino, Esmeralda        n =   648 partidas
//!   alto   Diamante, Máster, GM, Retador  n = 4.142 partidas
//! ```
//!
//! (Ojo con el Oro: va en *medio*, no en *bajo*. La misma tabla está duplicada
//! en `fetch_tiers.py` porque el etiquetado es Python y el baremo es Rust; si
//! alguna vez se cambia, hay que cambiarla en los dos sitios.)
//!
//! El tramo *medio* es el más flaco del corpus —el emparejamiento de LA1 dejó
//! pocas partidas de Oro-Esmeralda etiquetadas— pero aun así son ~1.290
//! jugadores por puesto, de sobra para nueve deciles.
//!
//! # Qué se mide y qué no
//!
//! Las tasas por minuto usan `gameDuration` de la partida entera, que es el
//! mismo denominador que usa Riot en sus `challenges` (comprobado: su
//! `goldPerMinute` cuadra con `goldEarned / (gameDuration / 60)` hasta el
//! tercer decimal).
//!
//! Las tres métricas de minuto 15 (`gold_diff_15`, `xp_diff_15`, `cs_diff_15`)
//! se miden contra el rival de línea —el mismo `teamPosition` en el otro
//! equipo— y sólo cuando el emparejamiento es 1 a 1. Se resuelven al 99,9% de
//! las partidas; el resto son lobbies con roles repetidos.
//!
//! Dos métricas son casi todo ceros en este corpus y hay que leerlas con
//! cuidado: `control_wards` (la mediana es 0 en cuatro de los cinco puestos) y
//! `solo_kills`. No están mal medidas —`visionWardsBoughtInGame` dice lo mismo
//! que `controlWardsPlaced`— es que en LA1 no se compran centinelas de control.
//! El percentil las trata como discretas y devuelve el rango medio del bloque
//! empatado, así que "0 centinelas de control" da percentil 35 en TOP y no 0.

